//Start of the ROM data, after the 16-byte iNES header.
#define ROM_START (LWRAM + 0x10)
//LWRAM address of a bank's first byte.
#define ROM_BANK(bank) (ROM_START + (bank) * 0x4000)
//LWRAM address of an NES address in a bank.
#define ROM_ADDR(bank, addr) (ROM_BANK(bank) + ((addr) & 0x3FFF))
//ROM_ADDR as a byte pointer.
#define ROM_PTR(bank, addr) ((Uint8 *)ROM_BANK(bank) + ((addr) & 0x3FFF))
//Picks the US or Japanese ROM address. Build with make JP=1 for the Japanese ROM.
#ifdef FF1_JP
#define ROM_VER(us, jp) (jp)
#else
#define ROM_VER(us, jp) (us)
#endif

